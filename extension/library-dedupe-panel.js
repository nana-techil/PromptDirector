function readable(value, key = '', names = new Map(), contentLabel = value => value) {
  if (value == null) return '';
  if (Array.isArray(value)) return value.map(v => readable(v, key, names, contentLabel)).filter(Boolean).join('\n');
  if (typeof value === 'object') return Object.entries(value).filter(([k]) => !DISPLAY_INTERNAL.has(k))
    .map(([k, v]) => readable(v, k, names, contentLabel)).filter(Boolean).join('\n');
  if (typeof value === 'string' && /Ids?$/u.test(key) && /^\$media:\d+:/u.test(value)) {
    return t('第 {count} 份素材', { count: Number(value.split(':')[1]) + 1 });
  }
  if (key === 'nodeId') return names.get(value) || t('未命名标签');
  if (key === 'contentTypeId' || key === 'pathIds') return contentLabel(value);
  if (typeof value === 'boolean') return '';
  return `${KEY_NAMES[key] ? `${t(KEY_NAMES[key])}：` : ''}${value}`;
}
function comparisonText(section, fields, entry, other, names, contentLabel) {
  const text = readable(fields[section], '', names, contentLabel);
  if (section !== 'media') return text;
  const notes = (entry.mediaAssets || []).flatMap((asset, index) => {
    const counterpart = other.mediaAssets?.[index];
    if (!counterpart) return [t('第 {count} 份素材：另一案例没有此位置的素材', { count: index + 1 })];
    if (!mediaIdentity(asset) || !mediaIdentity(counterpart)) return [t('第 {count} 份素材：原件尚未核对', { count: index + 1 })];
    return mediaIdentity(asset) === mediaIdentity(counterpart) ? [] : [t('第 {count} 份素材：原件内容不同', { count: index + 1 })];
  });
  return [...notes, text].join('\n');
}
function dateText(value) { return value && Number.isFinite(Date.parse(value)) ? new Date(value).toLocaleString() : t('未知'); }

